// RenderHTML generates the HTML email digest
func RenderHTML(payload DigestPayload) (string, error) {
	tmpl, err := template.New("digest_html").Parse(emailHTMLTemplate)
	if err != nil {
		return "", fmt.Errorf("failed to parse email template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, payload); err != nil {
		return "", fmt.Errorf("failed to render email template: %w", err)
	}

	return buf.String(), nil
}

// RenderPlainText generates plain text fallback for email clients
func RenderPlainText(payload DigestPayload) string {
	var sb strings.Builder

	sb.WriteString("===================================================================\n")
	sb.WriteString(fmt.Sprintf("  KubeJobs Digest — %d New Positions Discovered\n", len(payload.NewJobs)))
	sb.WriteString("===================================================================\n\n")

	for i, j := range payload.NewJobs {
		sb.WriteString(fmt.Sprintf("[%d] %s — %s\n", i+1, j.Title, j.CompanyName))
		sb.WriteString(fmt.Sprintf("    Location:    %s (Remote: %s)\n", j.Location, j.RemoteType))
		sb.WriteString(fmt.Sprintf("    Skills:      %s\n", strings.Join(j.MatchedSkills, ", ")))
		if j.SnippetMatch != "" {
			sb.WriteString(fmt.Sprintf("    Proof:       %s\n", j.SnippetMatch))
		}
		sb.WriteString(fmt.Sprintf("    Apply:       %s\n\n", j.CanonicalURL))
	}

	sb.WriteString("-------------------------------------------------------------------\n")
	sb.WriteString("Generated by getfetch (https://github.com/bikrams/getfetch)\n")

	return sb.String()
}
